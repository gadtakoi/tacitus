"""SQLAlchemy models for Tacitus application.

This module defines all ORM models mapped to PostgreSQL tables.
All models inherit from the shared :class:`Base` declarative base.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    String,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    """Base class for all SQLAlchemy models."""


class Stream(Base):
    """Stream configuration stored in PostgreSQL.

    Represents a MediaMTX stream path. The ``name`` column must be unique
    across the table.

    Publish/read credentials are intentionally not stored here: MediaMTX 1.15.1
    has no per-path credential parameters, so access is granted through the
    global ``authInternalUsers`` list instead (ADR-012).
    """

    __tablename__ = "streams"

    # Primary key: sequential integer identifier.
    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    # Unique stream name (e.g. ``cam1``).
    name: Mapped[str] = mapped_column(String(64), nullable=False)
    # Stream source; ``publisher`` means the stream is published to MediaMTX.
    source: Mapped[str] = mapped_column(String(512), nullable=False, default="publisher")
    # Whether recording/archive cleanup is enabled for this stream.
    record_enabled: Mapped[bool] = mapped_column(default=True, nullable=False)
    # Timestamp when the record was created (UTC).
    # ``timezone=True`` keeps the column TIMESTAMPTZ, matching the original
    # Alembic migration; without it SQLAlchemy would emit plain TIMESTAMP
    # on fresh ``create_all`` and naive datetimes would lose offset info.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )
    # Timestamp of the last update; automatically refreshed on each update.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        onupdate=lambda: datetime.now(UTC),
        nullable=False,
    )

    __table_args__ = (UniqueConstraint("name", name="uq_stream_name"),)


class User(Base):
    """Application user account.

    Stores the minimal set of credentials required for authentication.
    Passwords are never stored in plain text; only ``pbkdf2_sha256`` hashes
    are persisted.
    """

    __tablename__ = "users"

    # Primary key: random UUID generated by the application.
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    # Unique login name chosen by the user.
    username: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    # Passlib hash of the user's password (never the plain password).
    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)
    # Whether the account can be used to authenticate.
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    # Timestamp when the account was created (UTC).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )
    # Timestamp of the last account update (UTC).
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        onupdate=lambda: datetime.now(UTC),
        nullable=False,
    )

    # Refresh tokens issued for this user. Deleting a user cascades to its
    # refresh tokens so no orphaned records remain.
    refresh_tokens: Mapped[list[RefreshToken]] = relationship(
        "RefreshToken",
        back_populates="user",
        cascade="all, delete-orphan",
        lazy="selectin",
    )


class RefreshToken(Base):
    """Refresh token issued to a user.

    The actual token string is never stored; only its SHA-256 hash is kept
    for lookup during refresh/logout operations. Tokens can be revoked before
    their natural expiration by setting ``revoked_at``.
    """

    __tablename__ = "refresh_tokens"

    # Primary key: random UUID.
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    # Owner of the refresh token.
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    # SHA-256 hash of the refresh token string (unique to prevent duplicates).
    token_hash: Mapped[str] = mapped_column(String(128), nullable=False, unique=True)
    # Moment when the token becomes invalid (UTC).
    expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )
    # Moment when the token was explicitly revoked; NULL means active.
    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    # Moment when the token was issued (UTC).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )

    # Relationship back to the owning user.
    user: Mapped[User] = relationship("User", back_populates="refresh_tokens")

    # No explicit index on ``token_hash``: ``unique=True`` already creates a
    # unique btree index, which serves the ``WHERE token_hash = ?`` lookups
    # used by refresh and logout. A second index would only cost writes.


class RevokedToken(Base):
    """Access token that has been explicitly revoked before its expiration.

    Only the JWT ID (``jti`` claim) is stored, not the full token string.
    Records older than the corresponding token expiration can be safely
    removed by a cleanup routine.
    """

    __tablename__ = "revoked_tokens"

    # Primary key: random UUID.
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    # JWT ID (``jti``) of the revoked access token.
    jti: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    # Original expiration time of the access token (UTC).
    expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )
    # Moment when the token was revoked (UTC).
    revoked_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )

    __table_args__ = (
        # Cleanup routine can efficiently remove expired records.
        Index("ix_revoked_tokens_expires_at", "expires_at"),
    )


class FailedLoginAttempt(Base):
    """Single failed login attempt.

    Records are aggregated by ``username`` over a sliding time window to
    enforce brute-force protection (e.g. lock account after 5 failures in
    15 minutes). Old records are periodically purged.
    """

    __tablename__ = "failed_login_attempts"

    # Primary key: random UUID.
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    # Username used in the failed attempt. Not indexed on its own: the
    # composite ``(username, created_at)`` index below has ``username`` as its
    # leftmost column and already serves lookups by username alone.
    username: Mapped[str] = mapped_column(String(64), nullable=False)
    # Client IP address at the moment of the attempt (optional).
    ip_address: Mapped[str | None] = mapped_column(String(45), nullable=True)
    # Exact moment of the failed attempt (UTC).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )

    __table_args__ = (
        # Used to count failures for a user within a time window.
        Index("ix_failed_attempts_username_created", "username", "created_at"),
        # Cleanup routine removes records older than the brute-force window.
        Index("ix_failed_attempts_created_at", "created_at"),
    )


class SecurityEvent(Base):
    """Security-related event recorded for monitoring and alerting.

    Examples include successful/failed authentications, suspicious activity
    spikes (many 401/403 responses from one IP), and other notable events.
    Arbitrary structured context is stored in ``details`` as JSONB.
    """

    __tablename__ = "security_events"

    # Primary key: random UUID.
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    # Event classifier, e.g. ``auth.login.failed`` or
    # ``security.suspicious_activity``.
    event_type: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    # Client IP address related to the event (optional).
    ip_address: Mapped[str | None] = mapped_column(String(45), nullable=True)
    # Username related to the event, if known (optional).
    username: Mapped[str | None] = mapped_column(String(64), nullable=True)
    # Arbitrary structured context (status code, count, user agent, etc.).
    details: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    # Exact moment when the event was recorded (UTC).
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(UTC),
        nullable=False,
    )

    __table_args__ = (
        # Detect suspicious activity spikes from a single IP within a window.
        Index("ix_security_events_ip_created", "ip_address", "created_at"),
        # Cleanup and time-range queries.
        Index("ix_security_events_created_at", "created_at"),
    )
